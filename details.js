openExerciseModal = function(id) {
  const ex = exercises.find(x => x.id === id);
  if (!ex) return;

  ensureExerciseModal();
  const rep = exerciseReplacements[id];
  const guide = rep?.guide || exerciseGuides[id] || g(
    `${ex.desc}|Выполняй движение медленно и под контролем.|Остановись, если появляется боль.`,
    'Сохраняй свободное дыхание.',
    'Не увеличивай амплитуду ценой техники.'
  );
  const detail = exerciseDetails[id] || {};
  const steps = detail.steps || guide.steps;
  const check = detail.check || guide.tip;
  const breath = detail.breath || 'Дыши свободно и не задерживай дыхание во время усилия.';
  const scale = detail.scale || 'Уменьши амплитуду, темп или нагрузку, если не получается сохранять технику.';
  const p = profileFor(ex);

  document.getElementById('exerciseModalContent').innerHTML = `
    <p class="eyebrow">Инструкция к упражнению</p>
    <h2 id="exerciseModalTitle">${ex.name}</h2>
    <div class="modal-tags tags">
      <span class="tag">${labels.type[ex.type]}</span>
      <span class="tag">${levelNamesShort[p.difficulty]}</span>
      <span class="tag">${ex.dose}</span>
      ${ex.places.map(x => `<span class="tag">${labels.place[x]}</span>`).join('')}
    </div>
    <p class="modal-intro">${ex.desc}</p>
    ${buildVisualBlock(ex)}
    <div class="instruction-grid instruction-grid-detailed">
      <div class="instruction-main detailed-steps">
        <h3>Как выполнять</h3>
        <ol class="steps-list">${steps.map(s => `<li>${s}</li>`).join('')}</ol>
      </div>
      <aside class="instruction-side">
        <div class="instruction-note good">
          <strong>Что контролировать</strong>
          <p>${check}</p>
        </div>
        <div class="instruction-note info">
          <strong>Дыхание</strong>
          <p>${breath}</p>
        </div>
        <div class="instruction-note neutral">
          <strong>Если пока сложно</strong>
          <p>${scale}</p>
        </div>
        <div class="instruction-note warning">
          <strong>Частая ошибка</strong>
          <p>${guide.mistake}</p>
        </div>
      </aside>
    </div>
    <div class="modal-safety"><strong>Безопасность:</strong> прекрати упражнение при острой боли, выраженном головокружении, внезапной слабости или необычной одышке. Не увеличивай вес, темп или амплитуду, если из-за этого теряется контроль движения.</div>
  `;

  const modal = document.getElementById('exerciseModal');
  modal.classList.remove('hidden');
  document.body.classList.add('modal-open');
  startVisual(ex);
  modal.querySelector('.modal-close').focus();
};
